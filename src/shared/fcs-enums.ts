// Steam ガイド「MODガイド ダイアログの条件、効果、イベントの一覧」(Lucius) の検証結果に基づく。

export type DialogConditionKind = "always" | "bool" | "int" | "tag";

/** 判定されず常に成立する (スコアだけ加算される) 条件。 */
const alwaysTrueConditions = new Set([0, 6, 15, 34, 51, 80]);

/** 数値を返し、比較方法 (compare by) で Value と比べる条件。それ以外は真偽値を返す。 */
