const atLeastConditions = new Set([1, 2, 3, 40, 47, 69]);

/** 許可リスト / 拒否リスト方式のタグ条件 (DC_HAS_TAG, DC_PERSONALITY_TAG) と tag の列挙型。 */
const tagConditions = new Map<number, string>([
  [23, "LongTermTag"],
  [26, "PersonalityTags"],
]);

export const getDialogConditionKind = (conditionName: number): DialogConditionKind => {
  if (alwaysTrueConditions.has(conditionName)) {
    return "always";
  }
  if (tagConditions.has(conditionName)) {
    return "tag";
  }
  if (integerConditions.has(conditionName)) {
    return "int";
  }
  return "bool";
};

export const isAtLeastCondition = (conditionName: number) => atLeastConditions.has(conditionName);

export const getDialogConditionTagEnumName = (conditionName: number) =>
  tagConditions.get(conditionName);

